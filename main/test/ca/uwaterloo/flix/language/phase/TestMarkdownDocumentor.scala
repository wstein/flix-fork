  test("page.links.validation.01") {
    // Every link target `[text](target.md)` in generated pages must correspond to an actual page in the document set.
    val pages = document(
      """
        |pub trait Eq[a] {
        |    pub def eq(x: a, y: a): Bool
        |}
        |
        |pub enum Option[t] {
        |    case None
        |    case Some(t)
        |}
        |
        |pub enum Result[t, e] {
        |    case Ok(t)
        |    case Err(e)
        |}
        |
        |mod Math {
        |    pub def add(x: Int32): Int32 = x
        |}
        |""".stripMargin)

    val linkPattern = """\[[^\]]+\]\(([^)]+\.md)\)""".r
    for ((pageName, content) <- pages) {
      for (m <- linkPattern.findAllMatchIn(content)) {
        val target = m.group(1)
        assert(pages.contains(target), s"Page $pageName contains broken link to '$target'")
      }
    }
  }

  test("diagram.svg.01") {
    // A trait with a supertrait generates a standalone SVG diagram file reference.
    withTempDir { dir =>
      implicit val flix: Flix = new Flix().setOptions(Options.TestWithLibNix.copy(outputPath = dir))
      generate(
        """
          |pub trait Base[a] {
          |    pub def base(x: a): Bool
          |}
          |
          |pub trait Derived[a] with Base[a] {
          |    pub def derived(x: a): Bool
          |}
          |""".stripMargin, dir)

      val derivedMd = dir.resolve("doc").resolve("Derived.md")
      assert(Files.exists(derivedMd))
      val text = Files.readString(derivedMd, StandardCharsets.UTF_8)
      assert(text.contains("![Trait Hierarchy](diagrams/Derived.svg)"))

      val svgPath = dir.resolve("doc").resolve("diagrams").resolve("Derived.svg")
      assert(Files.exists(svgPath), "Standalone SVG diagram Derived.svg should exist")
      val svgText = Files.readString(svgPath, StandardCharsets.UTF_8)
      assert(svgText.contains("<!-- Generated by the Flix compiler. Do not edit. -->"))
      assert(svgText.contains("Base"))
      assert(svgText.contains("Derived"))

      val xml = scala.xml.XML.loadString(svgText)
      assert(xml.label == "svg", "Generated SVG must be valid XML with root tag <svg>")
    }
