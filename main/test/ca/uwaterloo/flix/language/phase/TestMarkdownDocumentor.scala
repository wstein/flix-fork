  test("link.integrity.01") {
    // Every generated link must point at a page that was generated. A link to a page that does
    // not exist tells a reader something is documented when it is not.
    val pages = document(
      """
        |mod Api {
        |    pub enum Box[a] {
        |        case Box(a)
        |    }
        |
        |    trait Hidden[a] {
        |        pub def hidden(x: a): String
        |    }
        |
        |    instance Hidden[Box[a]] {
        |        pub def hidden(_x: Box[a]): String = "box"
        |    }
        |}
        |""".stripMargin)

    val md = page(pages, "Api.Box.md")
    // The instance is real API surface, so it is listed -- but `Hidden` is not public and has no page.
    assert(md.contains("`Hidden[Box[a]]` *(1 total)*"), md)
    assert(!md.contains("Hidden.md"), s"linked to a page that was never generated:\n$md")
    assert(!pages.contains("Api.Hidden.md"), pages.keys.toList.sorted.mkString(", "))
  }

  test("link.integrity.02") {
    // The same must hold across the whole standard library, which is where this first went wrong.
    val pages = document("pub def one(): Int32 = 1", options = Options.TestWithLibAll)

    val Link = """\]\(([A-Za-z0-9._]+\.md)\)""".r
    val broken = pages.values
      .flatMap(Link.findAllMatchIn(_).map(_.group(1)))
      .filterNot(pages.contains)
      .toList.distinct.sorted

    assert(broken.isEmpty, s"links to pages that do not exist: ${broken.mkString(", ")}")
  }

